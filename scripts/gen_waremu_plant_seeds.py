#!/usr/bin/env python3
"""Regenerate Source/Knowledge/WaremuPlantSeeds.lua from the waremu craft catalog.

Default catalog path (RoR-Interface sibling checkout):
  ../RoR-Interface/data/waremu-craft/catalog.json

Only keeps unambiguous plant->seed pairs (single seed after normalizing
\"Marsh Root\" / \"Marshroot\" and stripping seed/spore suffixes).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CATALOG = ROOT.parent / "RoR-Interface" / "data" / "waremu-craft" / "catalog.json"
DEFAULT_OUT = ROOT / "Source" / "Knowledge" / "WaremuPlantSeeds.lua"


def normalize_base(name: str) -> str:
    n = (name or "").lower().strip()
    n = re.sub(r"\s+seed$", "", n)
    n = re.sub(r"\s+spore$", "", n)
    return re.sub(r"[^a-z0-9]+", "", n)


def build_pairs(items: dict) -> list[tuple[int, int, str, str]]:
    seeds: dict[int, dict] = {}
    plants: dict[int, dict] = {}
    for uid_s, it in items.items():
        uid = int(uid_s)
        name = it.get("name") or ""
        role = it.get("roleHint")
        fam = it.get("craftFamily") or ""
        nl = name.lower()
        if role == "seed" or nl.endswith(" seed") or nl.endswith(" spore"):
            seeds[uid] = it
        elif fam in ("apothecary", "cultivating") and "seed" not in nl and "spore" not in nl:
            if role in ("main", "ingredient", None, ""):
                plants[uid] = it

    seed_by_base: dict[str, list[int]] = {}
    for uid, it in seeds.items():
        base = normalize_base(it.get("name") or "")
        if base:
            seed_by_base.setdefault(base, []).append(uid)

    pairs: list[tuple[int, int, str, str]] = []
    for uid, it in sorted(plants.items()):
        cands = seed_by_base.get(normalize_base(it.get("name") or "")) or []
        if len(cands) == 1:
            seed_uid = cands[0]
            pairs.append(
                (
                    uid,
                    seed_uid,
                    str(it.get("name") or ""),
                    str(seeds[seed_uid].get("name") or ""),
                )
            )
    return pairs


def render(pairs: list[tuple[int, int, str, str]]) -> str:
    lines = [
        "----------------------------------------------------------------",
        "-- StockPiler Knowledge/WaremuPlantSeeds",
        "-- Unambiguous plantUid -> seedUid from RoR-Interface waremu craft",
        "-- catalog (data/waremu-craft/catalog.json). Regenerated by",
        "-- scripts/gen_waremu_plant_seeds.py. Live harvest/refine links win.",
        "----------------------------------------------------------------",
        "",
        "StockPiler = StockPiler or {}",
        "StockPiler.WaremuPlantSeeds = StockPiler.WaremuPlantSeeds or {}",
        "local W = StockPiler.WaremuPlantSeeds",
        "",
        "-- plantUid -> seedUid (unique name match after marsh root/marshroot normalize)",
        "W.SEED_FOR_PLANT = {",
    ]
    for plant_uid, seed_uid, plant_name, seed_name in pairs:
        lines.append(
            f"    [{plant_uid}] = {seed_uid}, -- {plant_name} -> {seed_name}"
        )
    lines.extend(
        [
            "}",
            "",
            "function W.SeedUidForPlant(plantUid)",
            "    plantUid = tonumber(plantUid) or 0",
            "    if plantUid <= 0 then",
            "        return 0",
            "    end",
            "    return tonumber(W.SEED_FOR_PLANT[plantUid]) or 0",
            "end",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--catalog",
        type=Path,
        default=DEFAULT_CATALOG,
        help=f"waremu catalog.json (default: {DEFAULT_CATALOG})",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help=f"Lua output (default: {DEFAULT_OUT})",
    )
    args = parser.parse_args()
    if not args.catalog.is_file():
        print(f"Catalog not found: {args.catalog}", file=sys.stderr)
        return 1
    cat = json.loads(args.catalog.read_text(encoding="utf-8"))
    items = cat.get("items")
    if not isinstance(items, dict):
        print("catalog.json missing items object", file=sys.stderr)
        return 1
    pairs = build_pairs(items)
    args.out.write_text(render(pairs), encoding="utf-8")
    print(f"Wrote {len(pairs)} plant->seed pairs to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

